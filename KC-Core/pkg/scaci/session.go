// ParseEUI64 parses a hex string EUI64 to uint64
//
// Accepts:
//   - "1234567890abcdef" (16 hex chars)
//   - "0x1234567890ABCDEF" (with 0x prefix)
//
// Parameters:
//   - s: Hex-encoded EUI64 string
//
// Returns:
//   - uint64: Parsed EUI64 value
//   - error: Parse error if invalid format
func ParseEUI64(s string) (uint64, error) {
	// Remove optional 0x prefix
	if len(s) > 2 && (s[0:2] == "0x" || s[0:2] == "0X") {
		s = s[2:]
	}

	// Validate length (must be exactly 16 hex chars = 8 bytes)
	if len(s) != 16 {
		return 0, fmt.Errorf("EUI64 must be 16 hex characters, got %d", len(s))
	}

	// Parse as uint64 (big-endian)
	var result uint64
	_, err := fmt.Sscanf(s, "%x", &result)
	if err != nil {
		return 0, fmt.Errorf("invalid hex string: %w", err)
	}

	return result, nil
}

// ValidateAcOpId enforces SCACI §3.2: AC uses positive, strictly incrementing IDs
//
// Parameters:
//   - opId: Operation ID to validate
//
// Returns:
//   - error: Validation error if opId is invalid
func (s *Session) ValidateAcOpId(opId int64) error {
	// opId OpIDConnect (0) reserved for Connect handshake only
	if opId == OpIDConnect {
		return fmt.Errorf("opId 0 reserved for connect")
	}

	if opId <= 0 {
		return fmt.Errorf("AC opId must be positive, got %d", opId)
	}

	// First AC message after connect
	if s.AcOpIdCounter == 0 {
		return nil
	}

	if opId <= s.AcOpIdCounter {
		return fmt.Errorf("AC opId must increment (current: %d, got: %d)", s.AcOpIdCounter, opId)
	}

	return nil
}

// UpdateAcOpId records validated AC opId
func (s *Session) UpdateAcOpId(opId int64) {
	if opId > s.AcOpIdCounter && opId > 0 {
		s.AcOpIdCounter = opId
	}
}

