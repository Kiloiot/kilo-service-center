// generateSessionUUID generates a random 16-byte session UUID
//
// Uses crypto/rand for cryptographically secure random generation
//
// Returns:
//   - UUID16: Random session UUID
func generateSessionUUID() UUID16 {
	var uuid UUID16
	if _, err := rand.Read(uuid[:]); err != nil {
		// Fallback to timestamp-based UUID if random generation fails
		// This should never happen in practice
		timestamp := time.Now().UnixNano()
		binary.LittleEndian.PutUint64(uuid[0:8], uint64(timestamp))   //nolint:gosec // G115: Safe conversion for UUID generation
		binary.LittleEndian.PutUint64(uuid[8:16], ^uint64(timestamp)) //nolint:gosec // G115: Safe conversion for UUID generation
	}
	return uuid
}

// FormatUUID returns a hex string representation of a UUID
//
// Parameters:
//   - uuid: 16-byte UUID
//
// Returns:
//   - string: Hex-encoded UUID (32 characters)
func FormatUUID(uuid UUID16) string {
	return fmt.Sprintf("%x", uuid)
}

