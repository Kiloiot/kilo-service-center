// FieldType represents the expected type of a message field
type FieldType string

// Field type constants define the expected Go types for BSSCI message fields
const (
	// TypeInt64 is a signed 64-bit integer field type
	TypeInt64       FieldType = "int64"       // Signed 64-bit integer
	TypeUint64      FieldType = "uint64"      // Unsigned 64-bit integer (EUIs)
	TypeUint32      FieldType = "uint32"      // Unsigned 32-bit integer (counters)
	TypeUint16      FieldType = "uint16"      // Unsigned 16-bit integer (short addresses)
	TypeFloat64     FieldType = "float64"     // 64-bit floating point (SNR, RSSI)
	TypeString      FieldType = "string"      // UTF-8 string
	TypeBool        FieldType = "bool"        // Boolean
	TypeBytes       FieldType = "bytes"       // Byte array (fixed or variable length)
	TypeArray       FieldType = "array"       // Array (numeric or struct)
	TypeStruct      FieldType = "struct"      // Nested structure
	TypeInterface   FieldType = "interface{}" // Any type (config fields)
	TypeGeoLocation FieldType = "geoLocation" // [3]float64 geographic coordinates
	TypeSubpackets  FieldType = "subpackets"  // Subpacket details structure
)

// DL Data Result status values (BSSCI §5.14.1)
const (
	DLDataResultSent    = "sent"    // Downlink successfully sent
	DLDataResultExpired = "expired" // Downlink expired before transmission
	DLDataResultInvalid = "invalid" // Downlink rejected due to validation error
)

// FieldSpec defines the specification for a single message field
type FieldSpec struct {
	Name         string                 // Field name (matches MIOTY spec JSON key)
	Type         FieldType              // Expected field type
	Required     bool                   // Mandatory field (normalization fails if missing)
	DefaultValue interface{}            // Value to substitute when optional field absent
	SpecRef      string                 // BSSCI spec reference (e.g., "§5.8.1 line 234")
	ByteLength   int                    // For byte arrays: expected length (0 = variable)
	Validator    func(interface{}) bool // Custom validation (optional)
}

// ConditionalRule defines context-dependent field requirements
// Example: "responseExp requires dlOpen" (BSSCI §5.11.1)
type ConditionalRule struct {
	Condition func(map[string]interface{}) bool // Evaluates context
	Required  []string                          // Field names that must be present when condition true
	Forbidden []string                          // Field names that must be absent when condition true
	ErrorMsg  string                            // Human-readable error for violations
}

// MessageSpec defines the complete specification for a BSSCI message type
type MessageSpec struct {
	Command          string            // MIOTY command mnemonic (e.g., "statusRsp")
	SpecSection      string            // BSSCI spec section (e.g., "§5.8")
	Direction        CommandDirection  // Protocol direction (BS→SC, SC→BS, or Bidirectional) - Issue #3-4 Fix B1
	MandatoryFields  []FieldSpec       // Fields that must be present
	OptionalFields   []FieldSpec       // Fields that may be absent (with defaults)
	ConditionalRules []ConditionalRule // Context-dependent validation rules
}

