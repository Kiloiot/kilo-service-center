// IsCommandRegistered checks if a BSSCI command has normalization metadata
func IsCommandRegistered(command string) bool {
	_, exists := messageRegistry[command]
	return exists
}

// init populates the Direction field for all MessageSpec entries from CommandDirectionMap.
// This ensures every command has its protocol direction set for normalization gating (Issue #3-4 Fix B1).
func init() {
	for cmd, spec := range messageRegistry {
		if direction, exists := CommandDirectionMap[cmd]; exists {
			spec.Direction = direction
		}
		// Commands not in CommandDirectionMap will have Direction = "" (zero value)
		// which will be treated as "unknown" and default to skipping normalization (safe fallback)
	}
}

// RegisteredCommands returns the list of all commands with normalization metadata
// Useful for automation verification (check all handlers covered)
func RegisteredCommands() []string {
	commands := make([]string, 0, len(messageRegistry))
	for cmd := range messageRegistry {
		commands = append(commands, cmd)
	}
	return commands
}
